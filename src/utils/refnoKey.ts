/**
 * refno 归一化键（公共收口）
 *
 * 仓内多处需要把 `=24381/145018`、`24381/145018`、` 24381/145018 `、`24381_145018`
 * 等写法归一成同一个比较键。此前各处各写一份 `.trim().replace('/', '_')`，
 * 其中 `.replace('/', '_')` 只替换**首个**斜杠：多段 refno（如 `24381/145018/1`）
 * 归一化后残留斜杠（`24381_145018/1`），与下游期望的 `24381_145018_1` 永不相等，
 * 导致相等校验失败或查不到数据。统一在这里做「全量替换」以消除这类不一致。
 *
 * 前导 `=` 只剥一个：`=` 是 E3D 对绝对 refno 文本的外层标记而非 refno 内容；
 * 用 `^=`（不用 `^=+`、也不去字符串中部的 `=`）剥最外层一个，既覆盖 `=a/b` 输入，
 * 又不吞掉可能合法出现的其余 `=`——`==a/b` 属异常输入，剥一层后残留等号反而便于暴露。
 */

/**
 * 把 refno 文本归一成比较键：trim → 剥一个前导 `=` → 所有 `/` 换成 `_`。幂等。
 *
 * @param value 任意来源的 refno 文本；空值返回 `''`
 */
export function toRefnoKey(value: string | null | undefined): string {
  return String(value ?? '').trim().replace(/^=/, '').replace(/\//g, '_');
}
