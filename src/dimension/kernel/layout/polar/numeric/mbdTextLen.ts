/** 表外字符的宽度（mbdtextlen.pmlfnc:29）。 */
export const MBD_TEXT_LEN_FALLBACK = 1.02;

/** x / X 在原表里缺席（第 34/60 项是 s / S），按同值补齐（C9）。 */
const MISSING_GLYPH_WIDTHS: readonly (readonly [string, number])[] = [
  ['x', 0.5201],
  ['X', 0.6869],
];

function buildTable(): ReadonlyMap<string, number> {
  const table = new Map<string, number>();
  for (const [glyph, width] of MBD_TEXT_LEN_PML_ENTRIES) {
    // `findfirst` semantics: the first row wins when a glyph repeats.
    if (!table.has(glyph)) table.set(glyph, width);
  }
  for (const [glyph, width] of MISSING_GLYPH_WIDTHS) table.set(glyph, width);
  return table;
}

/** 去重并补齐 x / X 后的查表：112 + 2 = 114 键。 */
export const MBD_TEXT_LEN_TABLE: ReadonlyMap<string, number> = buildTable();

/** 文字长度（字高倍数）：逐码点查表累加，未命中加 `MBD_TEXT_LEN_FALLBACK`。 */
export function mbdTextLen(text: string): number {
  let total = 0;
  for (const glyph of text) {
    total += MBD_TEXT_LEN_TABLE.get(glyph) ?? MBD_TEXT_LEN_FALLBACK;
  }
  return total;
}
